import './telemetry-i18n.js';
import React from 'react';
import {act, fireEvent, render, screen, within} from '@testing-library/react';
import {configureStore} from '@reduxjs/toolkit';
import {Provider} from 'react-redux';
import {describe, expect, it} from 'vitest';
import TelemetryValuesTab from '../telemetry-values-tab.jsx';
import fixtures from '../../../../../backend/tests/fixtures/viewer.json';

function renderWithPreferences(ui, timezone = 'UTC', locale = 'en-US') {
    const initial = {preferences: [{name: 'timezone', value: timezone}, {name: 'locale', value: locale}]};
    const store = configureStore({reducer: {preferences: (state = initial, action) =>
        action.type === 'setTimezone' ? {...state, preferences: state.preferences.map((pref) =>
            pref.name === 'timezone' ? {...pref, value: action.payload} : pref)} : state}});
    return {...render(<Provider store={store}>{ui}</Provider>), store};
}
const legacy = (name) => fixtures.legacy[name].telemetry;

describe('Common telemetry records generated by the backend', () => {
    it('renders historical GEOSCAN readings with units, order and collapsible raw bytes', () => {
        renderWithPreferences(<TelemetryValuesTab telemetry={legacy('housekeeping')} satellite="GEOSCAN-6" />);
        expect(screen.getByRole('heading', {name: 'GEOSCAN-6'})).toBeInTheDocument();
        expect(screen.getByText('Beacon ID')).toBeInTheDocument();
        expect(screen.getByText('Jan 12, 2026, 20:03:58')).toBeInTheDocument();
        const power = screen.getByRole('region', {name: 'Power system'});
        for (const value of ['8.203 V', '4.142 V', '222 mA', '0 mA', '13 °C', '12 °C', '3']) {
            expect(within(power).getByText(value)).toBeInTheDocument();
        }
        expect(power.textContent.indexOf('Battery pack voltage')).toBeLessThan(power.textContent.indexOf('Operating mode'));
        expect(screen.getByText('eps_reserve_22')).not.toBeVisible();
        fireEvent.click(screen.getByText('Raw fields and reserved bytes'));
        expect(screen.getByText('255')).toBeVisible();
    });

    it('updates spacecraft and reception clocks when the timezone preference changes', () => {
        const {store} = renderWithPreferences(<TelemetryValuesTab telemetry={legacy('housekeeping')}
            captureTime={1768248298} />, 'Europe/Athens', 'en-GB');
        expect(screen.getByText('Power system time (Europe/Athens)')).toBeInTheDocument();
        expect(screen.getByText('12 Jan 2026, 22:03:58')).toBeInTheDocument();
        expect(screen.getByText('Received (Europe/Athens)')).toBeInTheDocument();
        expect(screen.getByText('12 Jan 2026, 22:04:58')).toBeInTheDocument();
        act(() => store.dispatch({type: 'setTimezone', payload: 'UTC'}));
        expect(screen.getByText('12 Jan 2026, 20:03:58')).toBeInTheDocument();
    });

    it('accepts epoch zero and historical clock strings without offsets', () => {
        const {unmount} = renderWithPreferences(<TelemetryValuesTab telemetry={legacy('clock')} />,
            'Europe/Athens', 'en-GB');
        expect(screen.getByText('15 Nov 2023, 00:13:20')).toBeInTheDocument();
        unmount();
        renderWithPreferences(<TelemetryValuesTab telemetry={legacy('epoch')} />);
        expect(screen.getByText('Jan 1, 1970, 00:00:00')).toBeInTheDocument();
    });

    it('distinguishes unavailable readings, zero and negative values', () => {
        renderWithPreferences(<TelemetryValuesTab telemetry={legacy('unavailable')} />);
        expect(screen.getByText('Measured battery voltage')).toBeInTheDocument();
        expect(screen.getByText('4.2 V')).toBeInTheDocument();
        expect(screen.getAllByText('Unavailable')).toHaveLength(3);
        expect(screen.getByTitle('Sensor unavailable')).toHaveTextContent('Unavailable');
        expect(screen.queryByText(/Unavailable (V|mA|°C)/)).not.toBeInTheDocument();
        for (const value of ['0 %', '0 °C', '-171 mA']) expect(screen.getByText(value)).toBeInTheDocument();
        expect(screen.getByRole('region', {name: 'Other telemetry'})).toHaveTextContent('Custom count12');
    });

    it('renders backend supplied Colibri flags without interpreting bits', () => {
        renderWithPreferences(<TelemetryValuesTab telemetry={legacy('colibri')} />);
        const obc = screen.getByRole('region', {name: 'Onboard computer'});
        expect(within(obc).getByText('Reaction wheels')).toBeInTheDocument();
        expect(within(obc).getByText('No')).toBeInTheDocument();
        expect(within(obc).getByText('Camera')).toBeInTheDocument();
        expect(within(obc).getByText('Yes')).toBeInTheDocument();
    });

    it('keeps small currents readable and large currents in amperes', () => {
        renderWithPreferences(<TelemetryValuesTab telemetry={legacy('rs52s')} />);
        expect(screen.getByText('-125 mA')).toBeInTheDocument();
        expect(screen.getByText('1.5 A')).toBeInTheDocument();
        expect(screen.getByText('reserved_16')).not.toBeVisible();
    });

    it('renders a real UWE-4 capture with five groups and no invented spacecraft clock', () => {
        renderWithPreferences(<TelemetryValuesTab telemetry={fixtures.real.uwe4.telemetry} />);
        expect(screen.getAllByRole('region')).toHaveLength(5);
        const battery = screen.getByRole('region', {name: 'Battery A'});
        for (const value of ['4.2 V', '138 mA', '94 %', '11 °C']) {
            expect(within(battery).getByText(value)).toBeInTheDocument();
        }
        expect(screen.getByRole('region', {name: 'Satellite status'})).toHaveTextContent('30,217 s');
        expect(screen.getByRole('region', {name: 'Panel temperatures'})).toBeInTheDocument();
        expect(screen.queryByText('Spacecraft time (UTC)')).not.toBeInTheDocument();
        expect(screen.getByText('packet_id')).not.toBeVisible();
    });

    it('renders a new backend group without requiring satellite-specific UI code', () => {
        renderWithPreferences(<TelemetryValuesTab telemetry={legacy('custom')} />);
        const sensors = screen.getByRole('region', {name: 'Custom sensors'});
        expect(sensors.textContent.indexOf('New sensor')).toBeLessThan(sensors.textContent.indexOf('Pack current'));
        expect(sensors.textContent.indexOf('Pack current')).toBeLessThan(sensors.textContent.indexOf('Pack voltage'));
        expect(within(sensors).getByText('0 (raw)')).toBeInTheDocument();
        expect(screen.getAllByRole('region')).toHaveLength(1);
        expect(screen.getByRole('alert')).toHaveTextContent('no verified conversion');
    });

    it('explains image packets instead of showing empty measurement cards', () => {
        renderWithPreferences(<TelemetryValuesTab telemetry={legacy('warning')} />);
        expect(screen.getByRole('alert')).toHaveTextContent('GEOSCAN image packet detected.');
        expect(screen.queryByRole('region')).not.toBeInTheDocument();
    });
});
